import * as path from 'path';
import * as fs from 'fs/promises';
import * as crypto from 'crypto';
import { resolveWorkspacePath } from '../../tools/pathSafety';
import { errorCode, errorMessage } from '../../shared/errors';
import { EVREN_KOD_DIR, EVREN_KOD_SUBDIRS } from '../../shared/constants';

export interface FileSnapshot {
  id: string;
  filePath: string;
  originalContent: string | null; // dosya yeni oluşturulduysa null
  originalSha256: string;
  postExecutionSha256?: string;
  existsBefore: boolean;
  timestamp: number;
  toolCallId?: string;
  description?: string;
}

export interface RevertOptions {
  workspaceRoot?: string;
  force?: boolean;
}

export interface RevertResult {
  success: boolean;
  message: string;
  filePath: string;
  conflict?: boolean;
  currentSha256?: string;
  expectedSha256?: string;
  diff?: string;
}

interface SnapshotPersistence {
  dir: string;
  sessionId: string;
}

function sha256(content: string | null): string {
  if (content === null) return '';
  return crypto.createHash('sha256').update(content, 'utf-8').digest('hex');
}

/**
 * İki içerik arasındaki farkı kullanıcıya sunulabilir biçimde üretir.
 */
export function generateSimpleDiff(expected: string | null, actual: string | null, filePath: string): string {
  const expLines = (expected ?? '').split('\n');
  const actLines = (actual ?? '').split('\n');
  const lines: string[] = [
    `--- a/${filePath} (ajanın bıraktığı beklenen durum)`,
    `+++ b/${filePath} (diskteki mevcut değiştirilmiş durum)`
  ];
  const max = Math.max(expLines.length, actLines.length);
  for (let i = 0; i < max; i++) {
    const exp = expLines[i];
    const act = actLines[i];
    if (exp !== act) {
      if (exp !== undefined) lines.push(`-${exp}`);
      if (act !== undefined) lines.push(`+${act}`);
    } else {
      lines.push(` ${exp}`);
    }
  }
  return lines.slice(0, 100).join('\n');
}

export class SnapshotManager {
  private snapshots: FileSnapshot[] = [];
  private maxSnapshots = 50;
  private maxSnapshotBytes = 5 * 1024 * 1024;
  private persistence?: SnapshotPersistence;

  /**
   * Anlık görüntüleri `.evren-kod/snapshots/<oturumId>/` altında saklar; böylece
   * eklenti yeniden yüklendikten sonra da erişilebilir kalır.
   */
  public async attachSession(workspaceRoot: string | undefined, sessionId: string): Promise<void> {
    if (!workspaceRoot || !sessionId) {
      this.persistence = undefined;
      this.snapshots = [];
      return;
    }

    const dir = path.join(
      workspaceRoot,
      EVREN_KOD_DIR,
      EVREN_KOD_SUBDIRS.snapshots,
      sessionId.replace(/[^a-zA-Z0-9_-]/g, '_')
    );
    this.persistence = { dir, sessionId };
    this.snapshots = [];
    await this.ensureEvrenGitignore(workspaceRoot);

    try {
      const files = await fs.readdir(dir);
      const loaded: FileSnapshot[] = [];
      for (const file of files.filter((name) => name.endsWith('.json')).slice(-this.maxSnapshots)) {
        try {
          const raw = await fs.readFile(path.join(dir, file), 'utf-8');
          const parsed = JSON.parse(raw) as FileSnapshot;
          if (parsed && parsed.id && parsed.filePath) loaded.push(parsed);
        } catch {
          // Tek bozuk kayıt tüm oturumu engellememeli.
        }
      }
      this.snapshots = loaded.sort((a, b) => a.timestamp - b.timestamp).slice(-this.maxSnapshots);
    } catch {
      // Dizin yok: ilk oturum
    }
  }

  /**
   * Geri alma ve denetim verisi (`snapshots/`, `checkpoints/`, `worktrees/`,
   * `audit.log`) dosya içerikleri taşır ve yereldir; `.evren-kod/.gitignore` ile
   * depo commit'lerinden uzak tutulur. `wx` bayrağı: kullanıcı düzenlemesi
   * asla ezilmez (knowledge klasöründeki kalıbın `.evren-kod` kökü uygulaması).
   */
  private async ensureEvrenGitignore(workspaceRoot: string): Promise<void> {
    try {
      const dir = path.join(workspaceRoot, EVREN_KOD_DIR);
      await fs.mkdir(dir, { recursive: true });
      await fs.writeFile(
        path.join(dir, '.gitignore'),
        [
          '# Generated by Evren. Undo and audit data stays on this machine.',
          'snapshots/',
          'checkpoints/',
          'worktrees/',
          'audit.log',
          ''
        ].join('\n'),
        { encoding: 'utf-8', flag: 'wx' }
      );
    } catch {
      // Zaten var veya yazılamıyor: sessizce devam.
    }
  }

  private async persistSnapshot(snapshot: FileSnapshot): Promise<void> {
    if (!this.persistence) return;
    try {
      await fs.mkdir(this.persistence.dir, { recursive: true });
      await fs.writeFile(path.join(this.persistence.dir, `${snapshot.id}.json`), JSON.stringify(snapshot), {
        encoding: 'utf-8',
        mode: 0o600
      });
    } catch {
      // Kalıcılık ana iş akışını engellememeli.
    }
  }

  private async removePersisted(ids: string[]): Promise<void> {
    if (!this.persistence) return;
    for (const id of ids) {
      try {
        await fs.rm(path.join(this.persistence.dir, `${id}.json`), { force: true });
      } catch {
        // yoksay
      }
    }
  }

  /**
   * Bir dosyanın durumunu değiştirilmeden veya yazılmadan önce kopyalar ve SHA-256 hash'ini kaydeder.
   */
  public async createSnapshot(
    filePath: string,
    workspaceRoot?: string,
    toolCallId?: string,
    description?: string
  ): Promise<string> {
    const fullPath = workspaceRoot
      ? resolveWorkspacePath(filePath, workspaceRoot)
      : path.isAbsolute(filePath)
        ? filePath
        : filePath;

    let originalContent: string | null;
    let existsBefore: boolean;

    try {
      const stat = await fs.stat(fullPath);
      if (stat.size > this.maxSnapshotBytes) {
        throw new Error(
          `File snapshot for undo is too large (${Math.round(stat.size / 1024 / 1024)} MB, limit ${Math.round(this.maxSnapshotBytes / 1024 / 1024)} MB): ${filePath}`
        );
      }
      originalContent = await fs.readFile(fullPath, 'utf-8');
      existsBefore = true;
    } catch (err) {
      if (errorMessage(err).includes('File snapshot for undo is too large')) throw err;
      // "Dosya yok" ile "dosya okunamıyor" ayrımını koru: EACCES/EPERM gibi
      // hatalarda existsBefore=false demek, var olan bir dosyanın geri alırken
      // yanlışlıkla silinmesine yol açabilir.
      if (errorCode(err) !== 'ENOENT') throw err;
      existsBefore = false;
      originalContent = null;
    }

    const id = `snap_${Date.now()}_${Math.random().toString(36).slice(2, 7)}`;
    const snapshot: FileSnapshot = {
      id,
      filePath,
      originalContent,
      originalSha256: sha256(originalContent),
      existsBefore,
      timestamp: Date.now(),
      toolCallId,
      description
    };

    this.snapshots.push(snapshot);
    if (this.snapshots.length > this.maxSnapshots) {
      const removed = this.snapshots.shift();
      if (removed) void this.removePersisted([removed.id]);
    }

    await this.persistSnapshot(snapshot);
    return id;
  }

  /**
   * Araç çalıştırmasından hemen sonra dosyanın ulaştığı yeni durumun hash'ini kaydeder.
   * Bu hash, daha sonra rollback yapılırken kullanıcının yaptığı harici değişiklikleri
   * tespit etmek için referans alınır.
   */
  public async recordPostExecutionHash(
    snapshotId: string,
    workspaceRoot?: string
  ): Promise<string | undefined> {
    const snapshot = this.snapshots.find((s) => s.id === snapshotId);
    if (!snapshot) return undefined;
    const fullPath = workspaceRoot
      ? resolveWorkspacePath(snapshot.filePath, workspaceRoot)
      : path.isAbsolute(snapshot.filePath)
        ? snapshot.filePath
        : snapshot.filePath;

    try {
      const content = await fs.readFile(fullPath, 'utf-8');
      const hash = sha256(content);
      snapshot.postExecutionSha256 = hash;
      await this.persistSnapshot(snapshot);
      return hash;
    } catch {
      return undefined;
    }
  }

  /**
   * Belirli bir anlık görüntüye geri döner.
   * Rollback öncesinde SHA-256 kontrolü yapar: dosya ajanın yazmasından sonra
   * kullanıcı tarafından düzenlenmişse otomatik geri alma durdurulur ve diff sunulur.
   */
  public async revertSnapshot(
    snapshotId: string,
    optionsOrWorkspaceRoot?: string | RevertOptions
  ): Promise<RevertResult> {
    const options: RevertOptions =
      typeof optionsOrWorkspaceRoot === 'string'
        ? { workspaceRoot: optionsOrWorkspaceRoot }
        : (optionsOrWorkspaceRoot ?? {});

    const snapshot = this.snapshots.find((s) => s.id === snapshotId);
    if (!snapshot) {
      return { success: false, message: `Anlık görüntü bulunamadı: ${snapshotId}`, filePath: '' };
    }

    const fullPath = options.workspaceRoot
      ? resolveWorkspacePath(snapshot.filePath, options.workspaceRoot)
      : path.isAbsolute(snapshot.filePath)
        ? snapshot.filePath
        : snapshot.filePath;

    // Diskteki mevcut durumu ve SHA-256 hash'ini oku
    let currentContent: string | null = null;
    let fileExistsOnDisk = false;
    try {
      currentContent = await fs.readFile(fullPath, 'utf-8');
      fileExistsOnDisk = true;
    } catch (err) {
      if (errorCode(err) !== 'ENOENT') {
        return {
          success: false,
          message: `Dosya kontrolü başarısız: ${errorMessage(err)}`,
          filePath: snapshot.filePath
        };
      }
    }

    const currentSha = fileExistsOnDisk ? sha256(currentContent) : '';

    // Eşzamanlı değişiklik kontrolü (Optimistic Concurrency / Conflict Check)
    if (!options.force && snapshot.postExecutionSha256) {
      if (currentSha !== snapshot.postExecutionSha256) {
        // Dosya ajanın yazmasından sonra harici olarak (kullanıcı veya başka bir ajan) değiştirilmiş!
        const diff = generateSimpleDiff(currentContent, snapshot.originalContent, snapshot.filePath);
        return {
          success: false,
          conflict: true,
          message: `Çakışma tespit edildi: "${snapshot.filePath}" ajanın yazmasından sonra dışarıdan değiştirilmiş. Kullanıcı değişikliklerinin kaybolmaması için otomatik geri alma durduruldu.`,
          filePath: snapshot.filePath,
          currentSha256: currentSha,
          expectedSha256: snapshot.postExecutionSha256,
          diff
        };
      }
    }

    try {
      if (snapshot.existsBefore && snapshot.originalContent !== null) {
        await fs.mkdir(path.dirname(fullPath), { recursive: true });
        await fs.writeFile(fullPath, snapshot.originalContent, 'utf-8');
        this.removeSnapshots([snapshot.id]);
        await this.removePersisted([snapshot.id]);
        return {
          success: true,
          message: `"${snapshot.filePath}" önceki durumuna döndürüldü.`,
          filePath: snapshot.filePath
        };
      } else {
        // Dosya önceden yoktu; yeni oluşturulmuş, bu yüzden sil.
        if (fileExistsOnDisk) {
          try {
            await fs.unlink(fullPath);
          } catch (err) {
            if (errorCode(err) !== 'ENOENT') throw err;
          }
        }
        this.removeSnapshots([snapshot.id]);
        await this.removePersisted([snapshot.id]);
        return {
          success: true,
          message: `Yeni oluşturulan "${snapshot.filePath}" dosyası silinerek geri alındı.`,
          filePath: snapshot.filePath
        };
      }
    } catch (err) {
      return {
        success: false,
        message: `Geri alma başarısız: ${errorMessage(err)}`,
        filePath: snapshot.filePath
      };
    }
  }

  /**
   * En son dosya değişikliğini geri alır (Geri Al).
   */
  public async revertLast(optionsOrWorkspaceRoot?: string | RevertOptions): Promise<RevertResult> {
    if (this.snapshots.length === 0) {
      return { success: false, message: 'Geri alınacak dosya değişikliği yok.', filePath: '' };
    }

    const last = this.snapshots[this.snapshots.length - 1];
    if (!last) {
      return {
        success: false,
        message: 'Geri alınacak dosya değişikliği bulunamadı.',
        filePath: ''
      };
    }
    const res = await this.revertSnapshot(last.id, optionsOrWorkspaceRoot);
    if (!res.success && !res.conflict) {
      // Geri alma başarısızsa ve çakışma değilse anlık görüntüyü kaybetme.
      if (!this.snapshots.some((s) => s.id === last.id)) {
        this.snapshots.push(last);
      }
    }
    return res;
  }

  public getSnapshots(): FileSnapshot[] {
    return [...this.snapshots];
  }

  public getSnapshotByToolCall(toolCallId: string): FileSnapshot | undefined {
    return [...this.snapshots].reverse().find((s) => s.toolCallId === toolCallId);
  }

  public removeSnapshots(ids: string[]): void {
    const remove = new Set(ids);
    this.snapshots = this.snapshots.filter((s) => !remove.has(s.id));
  }

  /**
   * Yalnızca belleği temizler. Oturum değiştiğinde diskteki geri alma
   * kayıtları korunur; kullanıcı önceki oturuma dönebilir.
   */
  public async clear(): Promise<void> {
    this.snapshots = [];
  }
}
